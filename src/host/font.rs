/// A character of ASCII's dots on line `row` (0 to 7) of its 8, as `dots`
/// has them: the II+'s for $20 to $5F, lower case and the rest of ours
/// for $60 to $7F, its descenders on the 8th line; the controls blank.
pub fn ascii(char: u8, row: usize) -> u8 {
    let glyph = |rows: &[&str]| {
        rows[row]
            .bytes()
            .enumerate()
            .filter(|&(_, b)| b == b'#')
            .fold(0, |dots, (i, _)| dots | 1 << (i + 1))
    };
    match char & 0x7F {
        0x00..=0x1F => 0,
        c @ 0x20..=0x3F => dots(c, row),
        c @ 0x40..=0x5F => dots(c - 0x40, row),
        c => glyph(&LOWER[c as usize - 0x60]),
    }
}

