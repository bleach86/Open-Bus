/// A character's dots on line `row` (0 to 7) of its 8: bit 0 leftmost, 7
/// dots, the glyph's 5 in the middle; the 8th line is blank.
pub fn dots(char: u8, row: usize) -> u8 {
    if row == 7 {
        return 0;
    }
    FONT[char as usize][row]
        .bytes()
        .enumerate()
        .filter(|&(_, b)| b == b'#')
        .fold(0, |dots, (i, _)| dots | 1 << (i + 1))
}

